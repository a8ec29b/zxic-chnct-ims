#include "sms_pdu.h"

#include <assert.h>
#include <stdio.h>
#include <string.h>

int main(void)
{
    struct sms_deliver msg;
    const unsigned char gsm[] = {
        0x01,0x34,0x00,0x00,0x15,
        0x00,0x05,0x91,0x21,0x43,0xf5,0x00,0x00,
        0x62,0x11,0x42,0x80,0x00,0x10,0x23,0x05,0xe8,0x32,0x9b,0xfd,0x06
    };
    const unsigned char ucs_concat[] = {
        0x01,0x35,0x00,0x00,0x18,
        0x40,0x05,0x91,0x21,0x43,0xf5,0x00,0x08,
        0x62,0x11,0x42,0x80,0x00,0x10,0x23,0x08,
        0x05,0x00,0x03,0x2a,0x02,0x01,0x4e,0x2d
    };
    const unsigned char gsm_concat[] = {
        0x01,0x36,0x00,0x00,0x1b,
        0x40,0x05,0x91,0x21,0x43,0xf5,0x00,0x00,
        0x62,0x11,0x42,0x80,0x00,0x10,0x23,0x0c,
        0x05,0x00,0x03,0x2a,0x02,0x01,0xd0,0x65,0x36,0xfb,0x0d
    };
    assert(sms_decode_rp_data(gsm, sizeof(gsm), &msg) == 0);
    assert(msg.rp_reference == 0x34 && !strcmp(msg.sender, "+12345"));
    assert(!strcmp(msg.utf16be_hex, "00680065006C006C006F"));
    assert(msg.year == 2026 && msg.month == 11 && msg.day == 24);
    assert(msg.timezone_quarters == 32 && msg.epoch == 1795478401LL);
    assert(msg.total == 1 && msg.sequence == 1);
    assert(sms_decode_rp_data(ucs_concat, sizeof(ucs_concat), &msg) == 0);
    assert(msg.total == 2 && msg.sequence == 1 && msg.concat_reference == 42);
    assert(!strcmp(msg.utf16be_hex, "4E2D"));
    assert(sms_decode_rp_data(gsm_concat, sizeof(gsm_concat), &msg) == 0);
    assert(msg.total == 2 && msg.sequence == 1 && msg.concat_reference == 42);
    assert(!strcmp(msg.utf16be_hex, "00680065006C006C006F"));
    assert(sms_decode_rp_data(gsm, sizeof(gsm) - 1, &msg) == -1);
    puts("sms_pdu: ok");
    return 0;
}
